// Invisible end-to-end fixture for the Rust/Wasm frontend; real APIs, no external AI.
const {chromium}=require(process.env.TTX_PLAYWRIGHT||'../record/node_modules/playwright');
const {spawn}=require('child_process');
const fs=require('fs'),path=require('path'),assert=require('assert/strict');
const cwd=path.resolve(__dirname,'../..'),out=process.env.TTX_QA_OUT||path.join(cwd,'runs/rust-frontend-advanced');
(async()=>{
 fs.mkdirSync(out,{recursive:true});
 const port=process.env.TTX_QA_PORT||'8099',base=`http://127.0.0.1:${port}`;
 const child=spawn(process.env.TTX_BINARY||path.join(cwd,'target/release/ttx'),['--headless','--port',port,'--realizations','1'],{cwd,env:{...process.env,OPENROUTER_API_KEY:'',TTX_LLM_CASSETTE:''}});
 let log='',key,browser;const errors=[];
 const ready=new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(Error('startup timeout: '+log)),20000);const read=data=>{log+=data;const m=log.match(/EXCON access:.*token=([a-f0-9]+)/);if(m){key=m[1];clearTimeout(timer);resolve();}};child.stdout.on('data',read);child.stderr.on('data',read);child.on('exit',code=>{clearTimeout(timer);reject(Error('server exited '+code+': '+log));});});
 try{
  await ready;
  const api=async(route,body,token=key)=>{const r=await fetch(base+route,{method:body===undefined?'GET':'POST',headers:{Authorization:`Bearer ${token}`,'Content-Type':'application/json'},body:body===undefined?undefined:JSON.stringify(body)});const v=await r.json();assert.equal(r.status,200,JSON.stringify(v));return v;};
  const links=await api('/api/master/access'),mayor=links.players.find(p=>p.role==='mayor'),reviewer=links.evaluators[0];
  browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1100}});page.on('pageerror',e=>errors.push(e.message));
  const requests=[];page.on('request',r=>requests.push(r.url()));
  await page.goto(base+'/advanced.html?token='+key);
  await page.locator('#clock').filter({hasText:'Day'}).waitFor();
  assert(requests.some(url=>url.endsWith('.wasm')),'browser loads the compiled Rust module');
  assert(!requests.some(url=>/\/(common|interface|forecast|injects|player-preparation)\.js/.test(url)),'no legacy application JavaScript');
  await page.locator('#start-anyway').click();await page.locator('#turn').filter({hasText:'orders'}).waitFor();
  const initial=(await api('/api/state')).world;
  await page.getByRole('button',{name:'Innesco',exact:true}).click();
  await page.locator('#map').click({position:{x:270,y:180}});
  await page.locator('#physicalpreview h3').filter({hasText:'Effetto immediato previsto'}).waitFor();
  assert.deepEqual((await api('/api/state')).world,initial,'preview never mutates physics');
  await page.locator('#interventionreason').fill('Controlled Rust frontend review fixture');
  await page.locator('#applypreview').waitFor({state:'visible'});
  assert(!(await page.locator('#applypreview').isDisabled()),'current reviewed preview is applicable');
  await page.locator('#physicalpreview').screenshot({path:path.join(out,'intervention-preview.png')});
  await page.locator('#applypreview').click();
  await page.waitForFunction(()=>document.querySelector('#applypreview').disabled);
  const forecast=page.locator('#forecast-review');
  await forecast.getByLabel('Gruppi meteo').fill('1');await forecast.getByLabel('Orizzonti (minuti crescenti)').fill('1,2');
  const frozen=(await api('/api/state')).world;
  await forecast.locator('[data-compute]').click();
  await forecast.locator('[data-review]').waitFor({timeout:90000});
  assert.deepEqual((await api('/api/state')).world,frozen,'forecast stays private and read-only');
  const playerBefore=await api('/api/player/mayor');assert.equal(playerBefore.map.forecast_products.length,0);
  await forecast.screenshot({path:path.join(out,'forecast-private-desktop.png')});
  await forecast.locator('[data-role="mayor"]').check();
  await forecast.getByLabel('Fonte revisionata e motivazione').fill('Controlled reviewed bulletin');
  await forecast.locator('[data-reviewed]').check();assert(!(await forecast.locator('[data-publish]').isDisabled()));
  await forecast.locator('[data-publish]').click();
  await page.waitForFunction(()=>!document.querySelector('[data-reviewed]').checked);
  await page.waitForTimeout(150);
  assert.equal((await api('/api/player/mayor')).map.forecast_products.length,1);
  assert.equal((await api('/api/player/fire_commander')).map.forecast_products.length,0);
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'advanced UI has no mobile horizontal overflow');
  await forecast.screenshot({path:path.join(out,'forecast-mobile.png')});
  const player=await browser.newPage({viewport:{width:800,height:1280},hasTouch:true,isMobile:true});player.on('pageerror',e=>errors.push(e.message));
  const playerRequests=[];player.on('request',r=>{if(r.url().includes('/api/'))playerRequests.push(new URL(r.url()).pathname);});
  await player.goto(base+mayor.url);await player.locator('#thread-name').filter({hasText:'EXCON'}).waitFor();
  await player.locator('[data-view="map"]').click();await player.locator('#map').waitFor();
  assert(!playerRequests.some(p=>['/api/state','/api/master','/api/evaluator','/api/master/access'].includes(p)),'player uses only authorized role views');
  await player.screenshot({path:path.join(out,'player-reviewed-forecast.png'),fullPage:true});
  const evaluator=await browser.newPage({viewport:{width:1440,height:1000}});evaluator.on('pageerror',e=>errors.push(e.message));
  const writes=[];evaluator.on('request',r=>{if(r.method()==='POST')writes.push(r.url());});
  await evaluator.goto(base+reviewer.url);await evaluator.locator('#context').filter({hasText:'Day'}).waitFor();
  await evaluator.locator('#role').selectOption('mayor');await evaluator.locator('#assess').click();
  await evaluator.locator('#assessment').filter({hasText:'AI disabled'}).waitFor();
  assert.equal(writes.length,0,'evaluator remains read-only');
  await evaluator.screenshot({path:path.join(out,'evaluator-desktop.png'),fullPage:true});
  await evaluator.setViewportSize({width:390,height:844});
  assert.equal(await evaluator.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'evaluator has no mobile horizontal overflow');
  await evaluator.screenshot({path:path.join(out,'evaluator-mobile.png'),fullPage:true});
  // Resolution is a long request; EXCON must still deliver injects while it runs.
  await api('/api/master/settings',{speed:10});
  const live=await browser.newPage({viewport:{width:1440,height:1000}});live.on('pageerror',e=>errors.push(e.message));
  await live.goto(base+'/master.html?token='+key);await live.locator('#thread-name').filter({hasText:'Mayor'}).waitFor();
  await live.locator('#minutes').fill('1');await live.locator('#resolve').click();
  await live.locator('#turn').filter({hasText:'resolving'}).waitFor();
  await live.locator('#message-kind').selectOption('inject');
  await live.locator('#inject-title').fill('Live-turn inject');await live.locator('#inject-sender').fill('EXCON fixture');
  await live.locator('#text').fill('Information delivered while the turn is resolving.');
  assert(!(await live.locator('#send').isDisabled()),'live resolution does not block EXCON injects');
  await live.locator('#send').click();await live.locator('#send-status').filter({hasText:'Inviato'}).waitFor();
  assert((await api('/api/player/mayor')).inbox.some(m=>m.title==='Live-turn inject'));
  await live.locator('#turn').filter({hasText:'Turno 2'}).waitFor();
  await live.screenshot({path:path.join(out,'excon-live-turn.png')});
  assert.deepEqual(errors,[]);
  fs.writeFileSync(path.join(out,'manifest.json'),JSON.stringify({frontend:'Yew 0.23 / Rust WebAssembly',llm:'off',actions:['wasm asset loading','reviewed map intervention','private forecast','targeted publication','player authorized map only','evaluator filters and optional assessment','EXCON inject during live turn resolution'],errors},null,2));
  console.log('PASS: Rust/Wasm loading, physical preview, reviewed forecast, role privacy, evaluator read-only, desktop/mobile; no browser errors');
 }finally{await browser?.close();child.kill('SIGTERM');}
})().catch(e=>{console.error(e);process.exitCode=1;});
