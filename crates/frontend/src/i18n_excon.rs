/// `format!` with an Italian and an English template, chosen by the console language.
#[macro_export]
macro_rules! exfmt {
    ($it:literal, $en:literal $(, $a:expr)* $(,)?) => {
        if $crate::i18n::is_en() { format!($en $(, $a)*) } else { format!($it $(, $a)*) }
    };
}

