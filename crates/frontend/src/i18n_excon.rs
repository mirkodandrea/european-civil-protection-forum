/// "1 messaggio" / "2 messaggi" (English: "1 message" / "2 messages").
pub fn count_messages(n: usize) -> String {
    match (is_en(), n == 1) {
        (true, true) => format!("{n} message"),
        (true, false) => format!("{n} messages"),
        (false, true) => format!("{n} messaggio"),
        (false, false) => format!("{n} messaggi"),
    }
}

/// `format!` with an Italian and an English template, chosen by the console language.
#[macro_export]
macro_rules! exfmt {
    ($it:literal, $en:literal $(, $a:expr)* $(,)?) => {
        if $crate::i18n::is_en() { format!($en $(, $a)*) } else { format!($it $(, $a)*) }
    };
}

#[cfg(test)]
mod lang_tests {
    use super::*;
    #[test]
    fn hidden_panel_does_not_change_language() {
        set_ui_lang_if_visible(true, "it");
        set_ui_lang_if_visible(false, "en");
        assert!(!is_en());
        set_ui_lang_if_visible(true, "en");
        set_ui_lang_if_visible(false, "it");
        assert!(is_en());
        set_ui_lang("it");
    }
    #[test]
    fn other_player_languages_never_read_italian() {
        set_ui_lang("fr");
        assert!(is_en(), "templates fall back to English");
        let shown = ex("Iniziativa narrativa");
        assert_ne!(shown, "Iniziativa narrativa");
        assert_eq!(shown, crate::i18n_more::lookup("fr", "Narrative initiative").unwrap_or("Narrative initiative"));
        with_ui_lang("it", || assert_eq!(ex("Iniziativa narrativa"), "Iniziativa narrativa"));
        assert!(is_en(), "the previous language is restored");
        set_ui_lang("it");
    }
}
