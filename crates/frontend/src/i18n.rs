/// Replaces each `{}` in the translated template with the next argument.
pub fn tf(lang: &str, key: &'static str, args: &[&str]) -> String {
    let mut out = t(lang, key).to_string();
    for a in args {
        out = out.replacen("{}", a, 1);
    }
    out
}
